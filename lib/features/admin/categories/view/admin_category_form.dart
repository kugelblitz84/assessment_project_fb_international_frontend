class AdminCategoryFormPage extends ConsumerWidget {
  const AdminCategoryFormPage({super.key, this.id});
  final String? id;
  @override
  Widget build(BuildContext context, WidgetRef ref) => id == null
      ? const _CategoryForm()
      : AdminAsync(
          value: ref.watch(
            adminCategoryProvider((
              owner: ref.watch(adminOwnerProvider),
              id: id!,
            )),
          ),
          onRetry: () => ref.invalidate(
            adminCategoryProvider((
              owner: ref.watch(adminOwnerProvider),
              id: id!,
            )),
          ),
          builder: (item) => _CategoryForm(key: ValueKey(item.id), item: item),
        );
}

class _CategoryForm extends ConsumerStatefulWidget {
  const _CategoryForm({super.key, this.item});
  final AdminCategory? item;
  @override
  ConsumerState<_CategoryForm> createState() => _CategoryFormState();
}

class _CategoryFormState extends ConsumerState<_CategoryForm> {
  final form = GlobalKey<FormState>();
  late final imageKey = (owner: Object(), initialUrl: widget.item?.imageUrl);
  late final name = TextEditingController(text: widget.item?.name ?? '');
  late final slug = TextEditingController(text: widget.item?.slug ?? '');
  late final description = TextEditingController(
    text: widget.item?.description ?? '',
  );
  late final order = TextEditingController(
    text: '${widget.item?.sortOrder ?? 0}',
  );
  late bool active = widget.item?.isActive ?? true;
  @override
  void dispose() {
    name.dispose();
    slug.dispose();
    description.dispose();
    order.dispose();
    super.dispose();
  }

  Future<void> save() async {
    if (!form.currentState!.validate()) return;
    if (widget.item != null &&
        active != widget.item!.isActive &&
        !await adminConfirm(
          context,
          'Change category status?',
          'This changes category and related catalog visibility.',
        )) {
      return;
    }
    if (!mounted) return;
    final image = ref.read(adminImageProvider(imageKey));
    if (image.busy) return;
    final result = await ref
        .read(adminMutationProvider.notifier)
        .save(ApiEndpoints.adminCategories, {
          'name': name.text.trim(),
          if (slug.text.isNotEmpty) 'slug': slug.text,
          'description': description.text,
          'sortOrder': int.parse(order.text),
          'isActive': active,
          'imageUrl': image.url,
        }, id: widget.item?.id);
    if (!mounted) return;
    adminNotice(context, result, success: 'Category saved.');
    if (result.success) {
      if (widget.item != null) {
        ref.invalidate(
          adminCategoryProvider((
            owner: ref.read(adminOwnerProvider),
            id: widget.item!.id,
          )),
        );
      }
      context.go(AppRoutes.adminCategoriesPath);
    }
  }

  @override
  Widget build(BuildContext context) {
    final busy = ref.watch(adminMutationProvider);
    final image = ref.watch(adminImageProvider(imageKey));
    return Form(
      key: form,
      child: AdminPageBody(
        form: true,
        children: [
          Text(
            widget.item == null ? 'Add category' : 'Edit category',
            style: Theme.of(context).textTheme.headlineSmall,
          ),
          TextFormField(
            controller: name,
            enabled: !busy,
            decoration: const InputDecoration(labelText: 'Category name'),
            validator: AdminValidation.name,
          ),
          TextFormField(
            controller: slug,
            enabled: !busy,
            decoration: const InputDecoration(
              labelText: 'Slug (optional)',
              helperText: 'Generated by the backend when omitted.',
            ),
            validator: AdminValidation.slug,
          ),
          TextFormField(
            controller: description,
            enabled: !busy,
            maxLines: 3,
            decoration: const InputDecoration(labelText: 'Description'),
            validator: AdminValidation.description,
          ),
          TextFormField(
            controller: order,
            enabled: !busy,
            keyboardType: const TextInputType.numberWithOptions(signed: true),
            decoration: const InputDecoration(labelText: 'Sort order'),
            validator: AdminValidation.integer,
          ),
          SwitchListTile(
            contentPadding: EdgeInsets.zero,
            title: const Text('Active'),
            value: active,
            onChanged: busy ? null : (value) => setState(() => active = value),
          ),
          AdminImageField(fieldKey: imageKey, enabled: !busy),
          Wrap(
            spacing: 12,
            children: [
              FilledButton(
                onPressed: busy || image.busy ? null : save,
                child: Text(busy ? 'Saving…' : 'Save category'),
              ),
              TextButton(
                onPressed: busy
                    ? null
                    : () => context.go(AppRoutes.adminCategoriesPath),
                child: const Text('Cancel'),
              ),
            ],
          ),
        ],
      ),
    );
  }
}
